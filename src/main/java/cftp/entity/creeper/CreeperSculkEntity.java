public class CreeperSculkEntity extends CreeperElementalEntity {

    protected int ExplosionDiameter = 5;

    public CreeperSculkEntity(
            EntityType<? extends CreeperElementalEntity> entityType,
            World world
    ) {
        super(entityType, world);
    }

    public static DefaultAttributeContainer.Builder createAttributes() {
        return MobEntity.createMobAttributes()
                .add(EntityAttributes.MAX_HEALTH, 20)
                .add(EntityAttributes.MOVEMENT_SPEED, 0.25f)
                .add(EntityAttributes.ATTACK_DAMAGE, 1)
                .add(EntityAttributes.FOLLOW_RANGE, 20);
    }

    @Override
    protected int getElementalCreeperType() {
        return CreeperMath.CREEPER_TYPE.SCULK.getType();
    }

    @Override // TODO
    protected void explode() {
        if (this.getWorld() instanceof ServerWorld serverWorld) {

            SculkSpreadManager spreadManager = SculkSpreadManager.create();

            //SculkSpreadManager.create().spread();
            //Blocks.SCULK_CATALYST

            spreadManager.spread(BlockPos.ofFloored(this.getPos().offset(Direction.UP, 0.5)), 1);

            this.dead = true;
            this.playExplosionSound(serverWorld);
            this.spawnEffectsCloud();
            this.onRemoval(serverWorld, RemovalReason.KILLED);
            this.discard();
        }
    }

}
